// Schema-driven XDR walker shared by tools/coverage-report.mjs and
// tools/frequency/. The type universe is the JSON schema that the reference
// implementation (stellar CLI / rs-stellar-xdr) generates for LedgerCloseMeta;
// every union is a `oneOf` there, every enum an `enum`. Strkey-encoded unions
// (ScAddress, MuxedAccount, SignerKey) are classified by strkey prefix.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

export const STRKEY_UNIONS = {
  ScAddress: { G: "account", C: "contract", M: "muxed_account", B: "claimable_balance", L: "liquidity_pool", W: "muxed_contract" },
  MuxedAccount: { G: "ed25519", M: "muxed_ed25519" },
  SignerKey: { G: "ed25519", T: "pre_auth_tx", X: "hash_x", P: "ed25519_signed_payload" },
};

// JSON schema of LedgerCloseMeta from rs-stellar-xdr: `stellar xdr types schema`,
// or a file generated by the same rs-stellar-xdr version (XCK_LCM_SCHEMA, used
// in the checker image, which does not ship the stellar CLI).
export function lcmSchema() {
  const f = process.env.XCK_LCM_SCHEMA;
  const raw = f ? readFileSync(f) : execFileSync("stellar", ["xdr", "types", "schema", "--type", "LedgerCloseMeta"], { maxBuffer: 1 << 28 });
  return JSON.parse(raw.toString());
}

// Universe: union -> arms, enum -> values.
export function loadUniverse() {
  const schema = lcmSchema();
  const defs = { ...schema.definitions, LedgerCloseMeta: { oneOf: schema.oneOf } };
  const unions = {}, enums = {};
  const armName = (a) => (a.enum ? a.enum : a.required);
  for (const [name, d] of Object.entries(defs)) {
    if (d.oneOf) unions[name] = d.oneOf.flatMap(armName);
    else if (d.enum) enums[name] = [...d.enum];
  }
  for (const [name, m] of Object.entries(STRKEY_UNIONS)) if (defs[name]) unions[name] = Object.values(m);
  return { defs, unions, enums };
}

// walker(defs, { onHit, enter }):
//   onHit(type, arm, who)   called for every union arm / enum value taken
//   enter(typeName, value, who) -> new `who` or undefined; lets a caller
//                           re-attribute a subtree (e.g. to a transaction hash)
// Without onHit, hits are collected as "Type.arm" -> Set(who) in `hits`.
export function walker(defs, { onHit, enter } = {}) {
  const hits = {};
  const hit = onHit ?? ((t, arm, who) => (hits[`${t}.${arm}`] ??= new Set()).add(who));
  function walk(node, v, who, owner) {
    if (v === undefined) return;
    if (node.$ref) {
      const name = node.$ref.split("/").pop();
      return walkDef(name, v, who);
    }
    if (node.anyOf) {
      if (v === null) return;
      return walk(node.anyOf.find((x) => x.type !== "null"), v, who, owner);
    }
    if (node.oneOf) { // inline union (rare): attribute to owner
      const arm = typeof v === "string" ? node.oneOf.find((a) => a.enum?.includes(v)) : node.oneOf.find((a) => a.required && a.required[0] in v);
      if (arm?.properties) for (const [k, sub] of Object.entries(arm.properties)) walk(sub, v[k], who, owner);
      return;
    }
    if (Array.isArray(v)) {
      const items = node.items ?? {};
      if (Array.isArray(node.prefixItems)) v.forEach((x, i) => walk(node.prefixItems[i] ?? items, x, who, owner));
      else v.forEach((x) => walk(items, x, who, owner));
      return;
    }
    if (v && typeof v === "object" && node.properties) for (const [k, sub] of Object.entries(node.properties)) walk(sub, v[k], who, owner);
  }
  function walkDef(name, v, who) {
    const d = defs[name];
    if (!d) throw new Error(`no schema for ${name}`);
    if (enter) { const w = enter(name, v, who); if (w !== undefined) who = w; }
    if (STRKEY_UNIONS[name] && typeof v === "string") return hit(name, STRKEY_UNIONS[name][v[0]] ?? `?${v[0]}`, who);
    if (d.enum) return hit(name, v, who);
    if (d.oneOf) {
      let arm;
      if (typeof v === "string") arm = d.oneOf.find((a) => a.enum?.includes(v));
      else if (v && typeof v === "object") arm = d.oneOf.find((a) => a.required && a.required.length === 1 && a.required[0] in v);
      if (!arm) throw new Error(`${name}: value matches no arm: ${JSON.stringify(v).slice(0, 80)}`);
      const key = typeof v === "string" ? v : arm.required[0];
      hit(name, key, who);
      if (arm.properties) walk(arm.properties[key], v[key], who, name);
      return;
    }
    walk(d, v, who, name);
  }
  return { hits, walkDef };
}

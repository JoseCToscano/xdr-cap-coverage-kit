// Markdown rendering for backfill and live summaries.
const fmt = (n) => Number(n).toLocaleString("en-US");
const iso = (t) => (t ? new Date(t * 1000).toISOString().replace(".000Z", "Z") : "?");
const EXPL = {
  decode_failure: "a reader could not decode the ledger (localized per transaction)",
  disagreement: "readers decoded the same bytes to different canonical values",
  roundtrip_mismatch: "decode then encode was not byte-identical (Rust also checks SEP-51 JSON back to XDR)",
  js_precision: "a 64-bit value at or above 2^53 surfaced as a JS number in the SDK's high-level objects",
  first_seen: "union arm never seen in the mainnet baseline",
  long_tail: "union arm seen in fewer than 100 per million baseline mainnet transactions",
  bug_shape: "transaction has a shape behind a reproduced bug (frequency-study detectors)",
  shape_first_seen: "corpus / bug shape with no transaction in the baseline",
};
export function renderSummary(S, { title, intro = "" }) {
  let md = `# ${title}\n\n${intro}`;
  md += `| | |\n|---|---|\n`;
  md += `| Ledgers checked | ${fmt(S.ledgers)} (${S.ledger_min}–${S.ledger_max}${S.missing?.length ? `, ${S.missing.length} not in archive` : ""}) |\n`;
  md += `| Close times | ${iso(S.close_time_min)} – ${iso(S.close_time_max)} |\n`;
  md += `| Protocol | ${Object.entries(S.protocol).map(([p, n]) => `${p}: ${fmt(n)}`).join(", ")} |\n`;
  md += `| Transactions | ${fmt(S.txs)} |\n| Segments compared (ledger + envelopes + result metas), 3 readers each | ${fmt(S.segments)} |\n`;
  md += `| Checker time | ${(S.ms / 1000 / 3600).toFixed(2)} worker-hours |\n\n`;
  md += `## Readers\n\n| Reader | Library | Decoded | Byte round-trip |\n|---|---|---|---|\n`;
  md += `| JS | js-stellar-sdk 17.4.0 (js-xdr 5) | ${fmt(S.readers.js.ok)} | ${fmt(S.readers.js.roundtrip_ok)} |\n`;
  md += `| Go | go-stellar-sdk 0.9.0 xdr | ${fmt(S.readers.go.ok)} | ${fmt(S.readers.go.roundtrip_ok)} |\n`;
  md += `| Rust | rs-stellar-xdr 30.0.0 | ${fmt(S.readers.rust.ok)} | ${fmt(S.readers.rust.roundtrip_ok)} (SEP-51 JSON → XDR: ${fmt(S.readers.rust.json_roundtrip_ok)}) |\n\n`;
  md += `## Flags\n\n| Flag | Count | Distinct txs | Meaning |\n|---|---|---|---|\n`;
  for (const t of ["decode_failure", "disagreement", "roundtrip_mismatch", "js_precision", "first_seen", "long_tail", "bug_shape", "shape_first_seen"])
    md += `| \`${t}\` | ${fmt(S.flag_counts[t] ?? 0)} | ${fmt(S.flagged_txs[t] ?? 0)} | ${EXPL[t]} |\n`;
  md += `\n`;
  if (S.details.length) {
    md += `## Reader findings (all)\n\n`;
    for (const f of S.details.slice(0, 200)) {
      md += `- \`${f.type}\` ledger ${f.ledger}${f.tx ? ` tx \`${f.tx}\`` : ""}${f.reader ? ` reader ${f.reader}` : ""}${f.odd_reader ? ` odd reader **${f.odd_reader}**` : ""}${f.path ? ` at \`${f.path}\`` : ""}${f.at ? ` ${JSON.stringify(f.at)}` : ""}${f.hazards ? ` ${JSON.stringify(f.hazards).slice(0, 300)}` : ""}${f.err ? ` ${f.err.slice(0, 200)}` : ""}${f.triage ? ` — triage: ${f.triage}` : ""}\n`;
    }
    if (S.details.length > 200) md += `- … ${S.details.length - 200} more in the raw JSON\n`;
    md += `\n`;
  } else md += `No decode failures, disagreements, round-trip mismatches or JS precision hazards.\n\n`;
  const arms = Object.entries(S.arms).sort((a, b) => a[1].txs - b[1].txs || (a[0] < b[0] ? -1 : 1));
  const TITLES = { bug_shape: "Bug shapes", shape_first_seen: "First-seen shapes", first_seen: "First-seen arms", long_tail: "Long-tail arms" };
  for (const cls of ["bug_shape", "shape_first_seen", "first_seen", "long_tail"]) {
    const rows = arms.filter(([, a]) => a.class === cls);
    md += `## ${TITLES[cls]} (${rows.length})\n\n`;
    if (!rows.length) { md += `None.\n\n`; continue; }
    md += `| ${cls.includes("shape") ? "Shape" : "Arm"} | Txs | CAP (inferred) | Example txs |\n|---|---|---|---|\n`;
    for (const [k, a] of rows) md += `| \`${k}\` | ${fmt(a.txs)} | ${a.caps.join(", ") || "–"} | ${a.examples.map((e) => `\`${e.tx.slice(0, 12)}…\` (L${e.ledger})`).join(", ")} |\n`;
    md += `\n`;
  }
  return md;
}
export function renderBackfill(raw) {
  return renderSummary(raw.summary, { title: `Live checker backfill: ${raw.net} (${raw.name ?? "recent"})`,
    intro: `Generated by \`node tools/livecheck/backfill.mjs --report${raw.name && raw.name !== "recent" ? ` --name ${raw.name}` : ""}\` from the JSON next to this file. Every ledger is decoded by three independent readers and compared token by token (see tools/livecheck/README.md). Baseline for first-seen / long-tail: \`reports/raw/frequency.json\` (mainnet samples; the backfill window overlaps it, so first-seen is zero there by construction).\n\n` });
}

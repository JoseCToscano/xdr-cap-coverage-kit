// Union-arm and enum coverage of the corpus against the XDR types reachable
// from LedgerCloseMeta. The type universe is the JSON schema that the
// reference implementation (stellar CLI / rs-stellar-xdr) generates for
// LedgerCloseMeta; every union is a `oneOf` there, every enum an `enum`.
// Strkey-encoded unions (ScAddress, MuxedAccount, SignerKey) are classified
// by strkey prefix.
//
// Two scopes:
//   entry   the entry's own XDR value + its transaction's TransactionResultMetaV1
//           (tx_processing[tx_index]) + the ledger header. What the kit targets.
//   ledger  every LedgerCloseMeta in the corpus, all transactions included
//           (other testnet traffic in the same ledgers counts here).
//
// Usage: node tools/coverage-report.mjs [--check]
//   writes reports/coverage.md and reports/raw/coverage.json; --check fails
//   if the committed files differ from a fresh run (CI freshness check).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { readEntryLake, rustDecodeLcm } from "./galexie.mjs";
import { rustXdrVersion } from "./lib.mjs";
import { loadUniverse, walker as makeWalker } from "./xdr-walk.mjs";

const { defs, unions, enums } = loadUniverse();
const walker = () => makeWalker(defs);

const entries = readdirSync("corpus/entries").filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(`corpus/entries/${f}`, "utf8")));
const E = walker(), L = walker();
const lcmCache = new Map();
for (const e of entries) {
  E.walkDef(e.xdr.type, e.expected.json, e.id);
  if (!e.ledger) continue;
  const seq = e.ledger.sequence;
  if (!lcmCache.has(seq)) lcmCache.set(seq, rustDecodeLcm(readEntryLake(".", e).lcm));
  const lcm = lcmCache.get(seq);
  E.walkDef("LedgerHeaderHistoryEntry", lcm.v2.ledger_header, e.id);
  if (e.ledger.tx_index != null) E.walkDef("TransactionResultMetaV1", lcm.v2.tx_processing[e.ledger.tx_index], e.id);
}
for (const [seq, lcm] of [...lcmCache].sort((a, b) => a[0] - b[0])) L.walkDef("LedgerCloseMeta", lcm, String(seq));

const P30 = new Set(["ScAddress.muxed_contract", "StellarValueExt.signed_ms", "StellarValueExt.empty_tx_set_ms"]);
function table(universe) {
  return Object.keys(universe).sort().map((t) => {
    const arms = universe[t].map((a) => ({ arm: a, entry: [...(E.hits[`${t}.${a}`] ?? [])].sort(), ledger: (L.hits[`${t}.${a}`]?.size ?? 0) }));
    return { type: t, arms };
  });
}
const U = table(unions), N = table(enums);
const count = (rows, k) => rows.reduce((s, r) => s + r.arms.filter((a) => (k === "entry" ? a.entry.length : a.ledger) > 0).length, 0);
const total = (rows) => rows.reduce((s, r) => s + r.arms.length, 0);
const typesTouched = (rows, k) => rows.filter((r) => r.arms.some((a) => (k === "entry" ? a.entry.length : a.ledger) > 0)).length;
const summary = {
  xdr: rustXdrVersion(),
  universe: "stellar xdr types schema --type LedgerCloseMeta",
  entries: entries.length, entries_with_lcm: entries.filter((e) => e.ledger).length, ledgers: lcmCache.size,
  unions: { types: U.length, arms: total(U), entry_scope_arms: count(U, "entry"), ledger_scope_arms: count(U, "ledger"),
    entry_scope_types_touched: typesTouched(U, "entry"), ledger_scope_types_touched: typesTouched(U, "ledger") },
  enums: { types: N.length, values: total(N), entry_scope_values: count(N, "entry"), ledger_scope_values: count(N, "ledger") },
};
const pct = (a, b) => `${((100 * a) / b).toFixed(1)}%`;
let md = `# XDR coverage of the corpus\n\n<!-- generated by tools/coverage-report.mjs; do not edit. CI fails if stale. -->\n\n`;
md += `Universe: every union and enum in the JSON schema the reference implementation generates for \`LedgerCloseMeta\` (${summary.xdr}). `;
md += `Strkey-encoded unions (ScAddress, MuxedAccount, SignerKey) are classified by strkey prefix.\n\n`;
md += `- **entry scope**: each entry's own XDR value, plus (for entries with a ledger) its transaction's \`TransactionResultMetaV1\` and the ledger header. This is what the kit deliberately covers.\n`;
md += `- **ledger scope**: the ${summary.ledgers} distinct LedgerCloseMeta files that entries point to, in full, including other testnet transactions in those ledgers.\n\n`;
md += `| | Types | Arms/values | Entry scope | Ledger scope |\n|---|---|---|---|---|\n`;
md += `| Union arms | ${U.length} | ${total(U)} | ${count(U, "entry")} (${pct(count(U, "entry"), total(U))}) | ${count(U, "ledger")} (${pct(count(U, "ledger"), total(U))}) |\n`;
md += `| Enum values | ${N.length} | ${total(N)} | ${count(N, "entry")} (${pct(count(N, "entry"), total(N))}) | ${count(N, "ledger")} (${pct(count(N, "ledger"), total(N))}) |\n\n`;
md += `Corpus: ${summary.entries} entries, ${summary.entries_with_lcm} with a real LedgerCloseMeta.\n\n`;
md += `## Protocol 30 arms\n\n| Arm | Entry scope | Ledger scope (ledgers) |\n|---|---|---|\n`;
for (const r of U) for (const a of r.arms) if (P30.has(`${r.type}.${a.arm}`)) md += `| \`${r.type}.${a.arm}\` | ${a.entry.map((x) => `\`${x}\``).join(", ") || "**not covered**"} | ${a.ledger} |\n`;
md += `\n## Union arms by type\n\nOnly types with at least one arm seen in either scope are listed; the ${U.length - typesTouched(U, "ledger")} union types never seen in any corpus ledger are listed at the end.\n\n`;
md += `| Union | Arms seen (entry) | Arms seen (ledger) | Unseen arms |\n|---|---|---|---|\n`;
const unseenTypes = [];
for (const r of U) {
  const se = r.arms.filter((a) => a.entry.length), sl = r.arms.filter((a) => a.ledger);
  if (!sl.length && !se.length) { unseenTypes.push(r.type); continue; }
  const un = r.arms.filter((a) => !a.entry.length && !a.ledger).map((a) => a.arm);
  md += `| \`${r.type}\` | ${se.length}/${r.arms.length} | ${sl.length}/${r.arms.length} | ${un.length > 12 ? `${un.slice(0, 12).join(", ")}, ... (+${un.length - 12})` : un.join(", ")} |\n`;
}
md += `\nUnion types with no arm seen: ${unseenTypes.map((t) => `\`${t}\``).join(", ")}.\n`;
const json = JSON.stringify({ summary, unions: U, enums: N }, null, 2) + "\n";
mkdirSync("reports/raw", { recursive: true });
if (process.argv.includes("--check")) {
  const same = (p, s) => { try { return readFileSync(p, "utf8") === s; } catch { return false; } };
  if (!same("reports/coverage.md", md) || !same("reports/raw/coverage.json", json)) {
    console.error("reports/coverage.md is stale: run node tools/coverage-report.mjs and commit");
    process.exit(1);
  }
  console.log("coverage report is fresh");
} else {
  writeFileSync("reports/coverage.md", md);
  writeFileSync("reports/raw/coverage.json", json);
}
console.log(JSON.stringify(summary));

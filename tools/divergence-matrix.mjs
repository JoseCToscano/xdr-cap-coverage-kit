// Builds reports/divergence-matrix.md from what the runners and repros wrote:
//   reports/raw/{rust-cli,js,go,rust}.json    corpus runners (current versions)
//   repros/js-stellar-sdk/RESULTS.txt         pinned js-stellar-sdk versions
//   repros/x402-muxed-recipient/RESULTS.txt   pinned stellar-x402-policies commits
//   reports/raw/replay.json                   wallet-backend replay harness
// Usage: node tools/divergence-matrix.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const RUNNERS = [
  ["rust-cli", "stellar CLI (rs-stellar-xdr)"],
  ["rust", "Rust stellar-xdr crate"],
  ["go", "go-stellar-sdk"],
  ["js", "js-stellar-sdk"],
];
const raw = Object.fromEntries(RUNNERS.map(([k]) => [k, JSON.parse(readFileSync(`reports/raw/${k}.json`, "utf8"))]));
const entries = [...new Set(Object.values(raw).flat().map((r) => r.entry).filter(Boolean))].sort();
const cell = (rows) => {
  if (!rows.length) return "-";
  const ok = rows.filter((r) => r.ok && !r.na).length, na = rows.filter((r) => r.na).length, fail = rows.filter((r) => !r.ok).length;
  return `${fail ? `**${fail} FAIL** ` : ""}${ok} ok${na ? `, ${na} n/a` : ""}`;
};
let md = `# Divergence matrix\n\n<!-- generated by tools/divergence-matrix.mjs; do not edit. CI fails if stale. -->\n\n`;
md += `## Current decoders on the corpus\n\nEach cell counts the steps a runner executed for an entry (decode, byte-exact re-encode, hashes, LCM checks, semantic checks). n/a = the runner has no way to run that step (for example Go has no SEP-51 JSON encoder, so JSON-pointer checks are n/a there).\n\n`;
md += `| Entry | ${RUNNERS.map(([, n]) => n).join(" | ")} |\n|---|${RUNNERS.map(() => "---").join("|")}|\n`;
let fails = 0;
for (const e of entries) {
  md += `| \`${e}\` | ${RUNNERS.map(([k]) => cell(raw[k].filter((r) => r.entry === e))).join(" | ")} |\n`;
  fails += RUNNERS.reduce((s, [k]) => s + raw[k].filter((r) => r.entry === e && !r.ok).length, 0);
}
md += `| **total** | ${RUNNERS.map(([k]) => cell(raw[k].filter((r) => r.entry))).join(" | ")} |\n\n`;
// Steps where runners disagree (same entry+step, different ok).
const byStep = {};
for (const [k] of RUNNERS) for (const r of raw[k]) if (r.entry && !r.na) ((byStep[`${r.entry}|${r.step}`] ??= {})[k] = r.ok);
const disagree = Object.entries(byStep).filter(([, v]) => new Set(Object.values(v)).size > 1);
md += disagree.length ? `Steps where current decoders disagree:\n\n${disagree.map(([s, v]) => `- \`${s}\`: ${JSON.stringify(v)}`).join("\n")}\n\n`
  : `The current decoders agree on every step they all ran${fails ? "" : ", and no step failed"}. The divergences below are in older versions and in downstream code, reproduced against pinned builds.\n\n`;

md += `## Reproduced divergences (pinned versions)\n\n| Where | Issue / shape | Corpus entry | Before | After |\n|---|---|---|---|---|\n`;
const js = existsSync("repros/js-stellar-sdk/RESULTS.txt") ? readFileSync("repros/js-stellar-sdk/RESULTS.txt", "utf8").split("\n") : [];
const entryFor = { "1789": "scval-map-key-collision", "1785": "cap27-payment-muxed-max-id-to-muxed-zero-id", "1766": "cap38-pool-issuers-strkey-vs-bytes-order" };
for (const id of ["1766", "1785", "1789"]) {
  const lines = js.filter((l) => l.startsWith(`[#${id}] sdk-`));
  const vers = [...new Set(lines.map((l) => l.match(/sdk-([\d-]+)/)[1]))];
  const res = (v) => (lines.filter((l) => l.includes(`sdk-${v}:`)).every((l) => l.includes(": PASS")) ? "PASS" : "FAIL");
  if (vers.length) md += `| js-stellar-sdk | stellar/js-stellar-sdk#${id} | \`${entryFor[id]}\` | ${vers[0].replace(/-/g, ".")}: ${res(vers[0])} | ${vers.at(-1).replace(/-/g, ".")}: ${res(vers.at(-1))} |\n`;
}
const p30 = js.filter((l) => l.startsWith("[p30]"));
for (const ent of ["cap67", "cap84"]) {
  const ls = p30.filter((l) => l.includes(` ${ent}:`));
  if (!ls.length) continue;
  const v = (l) => l.match(/\[p30\] ([\d-]+)/)[1].replace(/-/g, ".");
  const t = (l) => (l.includes("=ERROR") ? "decode error" : l.includes("=DIFFERENT") ? "different address" : "same address");
  md += `| js-stellar-sdk | P30 probe, SAC transfer \`to\` = ${ent === "cap67" ? "M" : "W"} | \`${ent === "cap67" ? "cap67-sac-transfer-to-muxed-account" : "cap84-sac-transfer-to-muxed-contract"}\` | ${v(ls[0])}: ${t(ls[0])} | ${ls.slice(1).map((l) => `${v(l)}: ${t(l)}`).join(", ")} |\n`;
}
if (existsSync("repros/x402-muxed-recipient/RESULTS.txt")) {
  const x = readFileSync("repros/x402-muxed-recipient/RESULTS.txt", "utf8");
  const sec = x.split("== ").slice(1).map((s) => ({ head: s.split("\n")[0], m: /M: test result: ok/.test(s) ? "PASS" : "FAIL (NotAllowed)", w: (s.match(/W: W decode in this soroban-sdk: (.*)/) ?? [])[1] }));
  if (sec.length === 2) {
    md += `| stellar-x402-policies | merchant allowlist, SAC transfer to M of an allowlisted G | \`cap67-sac-transfer-to-muxed-account\` | ${sec[0].head.split(" ")[2]}: ${sec[0].m} | ${sec[1].head.split(" ")[2]}: ${sec[1].m} |\n`;
    md += `| stellar-x402-policies (soroban-sdk 28) | decode SAC transfer \`to\` = W | \`cap84-sac-transfer-to-muxed-contract\` | ${sec[0].head.split(" ")[2]}: ${sec[0].w} | ${sec[1].head.split(" ")[2]}: ${sec[1].w} |\n`;
  }
}
if (existsSync("reports/raw/replay.json")) {
  const rows = JSON.parse(readFileSync("reports/raw/replay.json", "utf8")).rows;
  const by = {};
  for (const r of rows) if (!/control/.test(r.Issue) && !/unshimmed|mock-rpc/.test(r.Build)) (by[r.Issue] ??= []).push(r);
  for (const [iss, rs] of Object.entries(by).sort()) {
    const pre = rs.find((r) => r.Build === "pre-fix"), fix = rs.find((r) => r.Build === "fix"), head = rs.find((r) => r.Build === "head");
    md += `| wallet-backend + PostgreSQL | stellar/${iss} | \`${rs[0].Entry}\` | ${pre ? `${pre.Commit}: ${pre.Got}` : "-"} | ${[fix && `${fix.Commit}: ${fix.Got}`, head && `HEAD ${head.Commit}: ${head.Got}`].filter(Boolean).join(", ")} |\n`;
  }
  md += `\nwallet-backend details, evidence rows and the SDK shim used on some commits: [replay-matrix.md](replay-matrix.md).\n`;
}
if (process.argv.includes("--check")) {
  if (!existsSync("reports/divergence-matrix.md") || readFileSync("reports/divergence-matrix.md", "utf8") !== md) {
    console.error("reports/divergence-matrix.md is stale: run node tools/divergence-matrix.mjs and commit");
    process.exit(1);
  }
  console.log("divergence matrix is fresh");
} else writeFileSync("reports/divergence-matrix.md", md);
console.log(`${entries.length} entries, ${fails} failing runner steps, ${disagree.length} disagreements`);
